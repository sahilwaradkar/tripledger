#!/usr/bin/env node
/**
 * Writes .env.local from Firebase CLI web SDK config for the linked project.
 * Requires: npx firebase login && npx firebase use --add
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const firebasercPath = join(root, "firebase", ".firebaserc");

function getDefaultProjectId() {
  const rc = JSON.parse(readFileSync(firebasercPath, "utf8"));
  const id = rc.projects?.default;
  if (!id || id === "demo-tripleger") {
    throw new Error(
      "Link a real project first: npx firebase use --add (from travel_expense/)",
    );
  }
  return id;
}

function listWebAppId(projectId) {
  const out = execSync(`npx firebase apps:list --project "${projectId}" --json`, {
    cwd: root,
    encoding: "utf8",
  });
  const data = JSON.parse(out);
  const apps = data.result ?? data;
  const web = (Array.isArray(apps) ? apps : []).find(
    (a) => (a.platform ?? a.appPlatform ?? "").toUpperCase() === "WEB",
  );
  if (!web?.appId) {
    throw new Error(
      `No web app in project "${projectId}". In Firebase Console add a Web app, then re-run.`,
    );
  }
  return web.appId;
}

function fetchSdkConfig(projectId, appId) {
  const out = execSync(
    `npx firebase apps:sdkconfig WEB "${appId}" --project "${projectId}" --json`,
    { cwd: root, encoding: "utf8" },
  );
  const parsed = JSON.parse(out);
  const cfg = parsed.result?.sdkConfig ?? parsed.sdkConfig ?? parsed;
  if (!cfg.apiKey || !cfg.projectId) {
    throw new Error("Unexpected sdkconfig output from Firebase CLI.");
  }
  return cfg;
}

function writeEnvLocal(cfg) {
  const lines = [
    `# Generated by npm run firebase:sync-env — ${new Date().toISOString()}`,
    `NEXT_PUBLIC_FIREBASE_API_KEY=${cfg.apiKey}`,
    `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${cfg.authDomain}`,
    `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${cfg.projectId}`,
    `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${cfg.storageBucket}`,
    `NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${cfg.messagingSenderId}`,
    `NEXT_PUBLIC_FIREBASE_APP_ID=${cfg.appId}`,
    `NEXT_PUBLIC_USE_FIREBASE_EMULATOR=false`,
    "",
  ];
  writeFileSync(join(root, ".env.local"), lines.join("\n"));
}

try {
  const projectId = getDefaultProjectId();
  const appId = listWebAppId(projectId);
  const cfg = fetchSdkConfig(projectId, appId);
  writeEnvLocal(cfg);
  console.log(`Wrote .env.local for project "${projectId}" (production, emulators off).`);
  console.log("Next: npm run firebase:deploy-rules && npm run dev");
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
}
